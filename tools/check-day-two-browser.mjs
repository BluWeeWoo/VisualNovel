import {chromium} from '@playwright/test';
import {freshState} from '../src/engine.js';
import {story} from '../src/story.js';
import {mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
mkdirSync('tmp/day-two-qa',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url());});
await page.goto('http://127.0.0.1:4173');
async function load(node,line=0){
 const s=freshState('Kai','they');s.node=node;s.line=line;
 await page.evaluate(s=>{localStorage.setItem('our-summer-v1-auto',JSON.stringify({date:Date.now(),state:s}));localStorage.setItem('our-summer-v1-settings',JSON.stringify({speed:0,motion:false,sound:false}));},s);
 await page.reload();await page.locator('[data-action="continue"]').first().click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.scene-art img')].every(i=>i.complete&&i.naturalWidth>0));
}
await load('d2Settling',story.d2Settling.lines.length-1);
await page.locator('[data-choice="0"]').click();
assert.match(await page.locator('#dialogue-text').textContent(),/Rowan/);
await load('d2Reveal');
assert.match(await page.locator('.event-cg').getAttribute('src'),/day-two\/garden-reveal.webp/);
await page.screenshot({path:'tmp/day-two-qa/garden-desktop.png'});
await load('d2PhoneOpen',story.d2PhoneOpen.lines.findLastIndex(l=>l.speaker==='Mom · SG'));
assert.equal(await page.locator('.morning-phone p').count(),6);
await page.screenshot({path:'tmp/day-two-qa/phone-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.locator('.morning-phone').evaluate(el=>el.scrollTop=el.scrollHeight);
await page.screenshot({path:'tmp/day-two-qa/phone-mobile.png'});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await load('d2Reveal',story.d2Reveal.lines.length-1);
await page.screenshot({path:'tmp/day-two-qa/garden-mobile.png'});
assert.match(await page.locator('.opening-end').textContent(),/day two/);
assert.deepEqual(errors,[]);console.log('Desktop/mobile garden, phone, choice transition, and ending passed. No browser errors.');
await browser.close();
